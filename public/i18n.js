export function normalizeLanguage(value) {
  if (SUPPORTED_LANGUAGES[value]) return value;
  const raw = String(value || '').toLowerCase();
  if (raw.startsWith('en')) return 'en';
  if (raw.startsWith('es')) return 'es';
  return 'pt-BR';
}

export function translate(language, key, variables = {}) {
  const lang = normalizeLanguage(language);
  const template = MESSAGES[lang]?.[key] ?? MESSAGES['pt-BR']?.[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : `{${name}}`
  );
}

export function getTranslationKeys(language = 'pt-BR') {
  return Object.keys(MESSAGES[normalizeLanguage(language)] || {});
}
